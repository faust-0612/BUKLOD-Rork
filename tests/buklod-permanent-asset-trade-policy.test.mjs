import assert from 'node:assert/strict';
// Node 22+ strips TypeScript syntax natively. Avoid esbuild/install in scope CI.
import {assessTrade,levelEffort,nextBuildPhase,businessOpeningGaps,mayUseItemForBuild,TRADE_POLICY}
  from '../src/lib/buklodAssetTradePolicy.ts';
const sample = {sellerId:'a',buyerId:'b',sellerAvailable:5,buyerSpendableBp:100,quantity:2,unitPriceBp:30,itemTradable:true,sellerVerified:true,buyerVerified:true,listingActive:true};
assert.equal(assessTrade(sample).totalBp,60);
assert.equal(assessTrade({...sample,buyerId:'a'}).allowed,false);
assert.equal(assessTrade({...sample,quantity:6}).allowed,false);
assert.equal(assessTrade({...sample,unitPriceBp:60}).allowed,false);
assert.equal(assessTrade({...sample,unitPriceBp:Infinity}).allowed,false);
assert.equal(assessTrade({...sample,quantity:Number.MAX_SAFE_INTEGER}).allowed,false);
assert.equal(assessTrade({...sample,itemTradable:false}).allowed,false);
assert.equal(assessTrade({...sample,sellerVerified:false}).allowed,false);
assert.equal(assessTrade({...sample,listingActive:false}).allowed,false);
assert.equal(TRADE_POLICY.newBpPerTrade,0);
assert.equal(TRADE_POLICY.rankLossOnPurchase,0);
assert.equal(TRADE_POLICY.qmpEffect,0);
assert.equal(nextBuildPhase([]),'materials');
assert.equal(nextBuildPhase(['materials','posts']),'frame');
assert.equal(nextBuildPhase(['materials','posts','frame','structure','finish']),null);
assert.throws(()=>nextBuildPhase(['posts']));
assert.throws(()=>nextBuildPhase(['materials','materials']));
assert.ok(levelEffort(10)>levelEffort(9));
assert.ok(levelEffort(9)>levelEffort(1));
assert.throws(()=>levelEffort(11));
assert.equal(mayUseItemForBuild(5,5),true);
assert.equal(mayUseItemForBuild(4,5),false);
const ready = {membershipApproved:true,orientationVerified:true,businessIdentityVerified:true,usableLotOrSlot:true,initialInventoryVerified:true,starterCapitalBp:100,requiredCapitalBp:100,regulatedActivityApproved:true};
assert.equal(businessOpeningGaps(ready).length,0);
assert.ok(businessOpeningGaps({...ready,orientationVerified:false}).includes('orientation'));
assert.ok(businessOpeningGaps({...ready,starterCapitalBp:99}).includes('capital'));
console.log('Permanent asset-trade policy tests passed');
