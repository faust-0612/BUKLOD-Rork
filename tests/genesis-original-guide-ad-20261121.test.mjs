import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('src/app/buklod-map.tsx');
const entry=read('src/features/season2/genesis/GenesisApprovedEntryMap.tsx');
const motion=read('src/features/season2/genesis/GenesisOriginalGuideMotion.tsx');
const ad=read('src/components/BuklodAdMobBanner.tsx');
const policy=read('src/lib/buklodGlobalAdController.ts');
const assets=read('src/features/season2/genesis/GenesisReliablePortraitImage.tsx');
test('genuine ad, never a fake sponsored card, owns the empty footer',()=>{
 assert.match(source,/BuklodAdMobBanner/);
 assert.match(source,/placement="home"/);
 assert.match(source,/placementId="genesis_entry_footer_banner"/);
 assert.match(source,/format="mediumRectangle"/);
 assert.match(source,/requireViewport/);
 assert.match(source,/showLabel/);
 assert.match(source,/marginTop:'auto'/);
 assert.doesNotMatch(source,/Genesis Study Pack|Get the Pack|Watch Now/);
 assert.match(ad,/useBuklodAdViewportGate/);
 assert.match(ad,/useAds\(\)/);
 assert.match(ad,/reserveBuklodPassiveAdRequest/);
 assert.match(ad,/onAdFailedToLoad/);
 assert.match(ad,/setFailed\(true\)/);
 assert.match(policy,/isBuklodPassiveAdAllowed/);
 assert.match(source,/onMenu=\{\(\) => setShowDirectory/);
 assert.match(source,/showDirectory \? <View style=\{styles\.districtPanel\}/);
});
test('identical baked nine-door image and original guide pixels are reused',()=>{
 assert.match(motion,/ORIGINAL_GUIDE_IN_MAP=require\('..\/..\/..\/..\/assets\/season2\/genesis\/world\/buklod-genesis-portrait-welcome-720x995\.jpg'\)/);
 assert.match(assets,/NATIVE_PORTRAIT=require/);
 assert.match(entry,/GenesisOriginalGuideMotion/);
 assert.match(entry,/DOORS\.map\(door=><Pressable/);
 assert.match(entry,/PROMPTS\.map\(prompt=><Pressable/);
 assert.doesNotMatch(motion,/data:image|fetch\(|https?:\/\//);
 assert.match(motion,/pointerEvents="none"/);
 assert.match(motion,/blink/);
 assert.match(motion,/armRotation/);
 assert.match(motion,/headRotation/);
 assert.match(motion,/if\(landscape \|\| !run\)return null/);
});
test('guide motion uses native driver and respects background, focus, motion settings',()=>{
 assert.match(motion,/useGenesisMotionAllowed/);
 assert.match(motion,/getGenesisDeviceQuality\('home'\)/);
 assert.match(motion,/if\(!run\)return/);
 assert.ok((motion.match(/useNativeDriver:true/g)||[]).length>=8);
 assert.match(motion,/blinking\.stop\(\)/);
 assert.match(motion,/waving\.stop\(\)/);
 assert.match(motion,/breathing\.stop\(\)/);
 assert.doesNotMatch(motion,/requestAnimationFrame\(|setInterval\(|awardBp|supabase\.rpc/);
});
