-- BUKLOD TODAY v2: shared public Dugtong with per-member privacy and 72h no-engagement rotation.
-- Additive: v1 remains intact for installed older clients; historical private entries stay private.
-- BP uses the same weekly source keys as v1 so migrating cannot pay twice.
create table if not exists public.buklod_today_tip_cycles_v2 (
 id bigint generated by default as identity primary key,
 tip_index integer not null references public.buklod_weekly_tips_v1(tip_index),
 started_at timestamptz not null default now(),
 last_engagement_at timestamptz not null default now()
);
create table if not exists public.buklod_today_tip_engagement_v2 (
 user_id uuid not null references public.profiles(id) on delete cascade,
 cycle_id bigint not null references public.buklod_today_tip_cycles_v2(id),
 reaction text check (reaction in ('helpful','heart','relate')),
 reacted_at timestamptz,
 dugtong text check (char_length(dugtong) between 30 and 1200),
 dugtong_at timestamptz,
 visibility text not null default 'public' check (visibility in ('public','private')),
 updated_at timestamptz not null default now(),
 primary key(user_id,cycle_id)
);
create index if not exists buklod_today_dugtong_feed_v2
 on public.buklod_today_tip_engagement_v2(cycle_id,dugtong_at desc)
 where dugtong is not null and visibility='public';
alter table public.buklod_today_tip_cycles_v2 enable row level security;
alter table public.buklod_today_tip_engagement_v2 enable row level security;
revoke all on public.buklod_today_tip_cycles_v2 from public,anon,authenticated;
revoke all on public.buklod_today_tip_engagement_v2 from public,anon,authenticated;
-- These tables intentionally have NO direct client access. All visibility is filtered in get RPC.

create or replace function public.ensure_buklod_today_tip_cycle_v2()
returns bigint language plpgsql volatile security definer set search_path='' as $func$
declare
 v_cycle public.buklod_today_tip_cycles_v2%rowtype;
 v_week date := date_trunc('week', now() at time zone 'Asia/Manila')::date;
 v_tip integer;
 v_last timestamptz;
begin
 -- Serializes both rotation and writes, including simultaneous first loads.
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('buklod:today-cycle-v2',0));
 select * into v_cycle from public.buklod_today_tip_cycles_v2
  order by id desc limit 1 for update;
 if not found then
  select tip_index into v_tip from public.buklod_weekly_tips_v1
   where enabled order by case when tip_index=mod(((v_week-date '2026-11-02')/7),12) then 0 else 1 end,tip_index limit 1;
  if v_tip is null then return null;end if;
  select max(greatest(reacted_at,dugtong_at)) into v_last
   from public.buklod_weekly_tip_interactions_v1
   where week_start=v_week and tip_index=v_tip;
  insert into public.buklod_today_tip_cycles_v2(tip_index,started_at,last_engagement_at)
   values(v_tip,now(),coalesce(v_last,now())) returning * into v_cycle;
  -- Preserve all existing same-week reflections but NEVER expose formerly private data.
  insert into public.buklod_today_tip_engagement_v2
   (user_id,cycle_id,reaction,reacted_at,dugtong,dugtong_at,visibility,updated_at)
  select user_id,v_cycle.id,reaction,reacted_at,dugtong,dugtong_at,'private',updated_at
    from public.buklod_weekly_tip_interactions_v1
   where week_start=v_week and tip_index=v_tip
  on conflict(user_id,cycle_id) do nothing;
 end if;
 if now() >= v_cycle.last_engagement_at + interval '72 hours'
    or not exists(select 1 from public.buklod_weekly_tips_v1 where tip_index=v_cycle.tip_index and enabled) then
   select tip_index into v_tip from public.buklod_weekly_tips_v1 where enabled
    order by case when tip_index>v_cycle.tip_index then 0 else 1 end,tip_index
    limit 1;
   if v_tip is not null then
    insert into public.buklod_today_tip_cycles_v2(tip_index,started_at,last_engagement_at)
      values(v_tip,now(),now()) returning * into v_cycle;
   end if;
 end if;
 return v_cycle.id;
end;
$func$;
revoke all on function public.ensure_buklod_today_tip_cycle_v2() from public,anon,authenticated;

create or replace function public.get_buklod_today_tip_v2()
returns jsonb language plpgsql volatile security definer set search_path='' as $func$
declare
 v_user uuid := (select auth.uid());
 v_cycle_id bigint;
 v_cycle public.buklod_today_tip_cycles_v2%rowtype;
 v_tip public.buklod_weekly_tips_v1%rowtype;
 v_my public.buklod_today_tip_engagement_v2%rowtype;
 v_feed jsonb;
 v_total bigint;
begin
 v_cycle_id:=public.ensure_buklod_today_tip_cycle_v2();
 if v_cycle_id is null then return null;end if;
 select * into v_cycle from public.buklod_today_tip_cycles_v2 where id=v_cycle_id;
 select * into v_tip from public.buklod_weekly_tips_v1 where tip_index=v_cycle.tip_index;
 if v_user is not null then
  select * into v_my from public.buklod_today_tip_engagement_v2
   where user_id=v_user and cycle_id=v_cycle_id;
 end if;
 select count(*) into v_total from public.buklod_today_tip_engagement_v2
  where cycle_id=v_cycle_id and visibility='public' and dugtong is not null;
 select coalesce(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
   'display_name',case when e.user_id=v_user then 'Ikaw'
     else coalesce(nullif(pg_catalog.btrim(p.first_name),''),
       nullif(pg_catalog.btrim(p.full_name),''),'BUKLOD member') end,
   'dugtong',e.dugtong,'created_at',e.dugtong_at,'is_mine',e.user_id=v_user
  ) order by e.dugtong_at desc),'[]'::jsonb) into v_feed
 from (
   select user_id,dugtong,dugtong_at
    from public.buklod_today_tip_engagement_v2
    where cycle_id=v_cycle_id and visibility='public' and dugtong is not null
    order by dugtong_at desc,user_id limit 30
 ) e
 left join public.profiles p on p.id=e.user_id;
 return pg_catalog.jsonb_build_object(
  'cycle_id',v_cycle_id,'cycle_started_at',v_cycle.started_at,
  'next_idle_at',v_cycle.last_engagement_at+interval '72 hours',
  'tip_index',v_tip.tip_index,'category',v_tip.category,'title',v_tip.title,
  'lead',v_tip.lead,'continuation',v_tip.continuation,'weekly_action',v_tip.weekly_action,
  'my_reaction',v_my.reaction,'my_dugtong',v_my.dugtong,
  'my_visibility',coalesce(v_my.visibility,'public'),
  'dugtongs',v_feed,'dugtong_total',v_total,
  'authenticated',v_user is not null,
  'points_enabled',(select count(*)=2 and coalesce(bool_and(r.is_active),false)
     from public.buklod_point_rules r where r.activity_type in ('weekly_tip_reaction','weekly_tip_dugtong'))
 );
end;
$func$;
revoke all on function public.get_buklod_today_tip_v2() from public,anon,authenticated;
grant execute on function public.get_buklod_today_tip_v2() to anon,authenticated;

create or replace function public.react_to_buklod_today_tip_v2(
 p_cycle_id bigint,p_reaction text default null,p_dugtong text default null,
 p_visibility text default null)
returns jsonb language plpgsql volatile security definer set search_path='' as $func$
declare
 v_user uuid := (select auth.uid());
 v_cycle_id bigint;
 v_week date := date_trunc('week',now() at time zone 'Asia/Manila')::date;
 v_existing public.buklod_today_tip_engagement_v2%rowtype;
 v_first_reaction boolean;
 v_first_dugtong boolean;
 v_changed_reaction boolean;
 v_changed_dugtong boolean;
 v_awarded integer := 0;
 v_points integer;
 v_ledger_id uuid;
begin
 if v_user is null or not exists(select 1 from public.profiles where id=v_user and is_active=true) then
  raise exception 'Active BUKLOD account required' using errcode='42501';
 end if;
 if p_reaction is null and p_dugtong is null and p_visibility is null then
  raise exception 'Choose a reaction, Dugtong or privacy setting';
 end if;
 if p_reaction is not null and p_reaction not in ('helpful','heart','relate') then
  raise exception 'Invalid reaction';
 end if;
 if p_visibility is not null and p_visibility not in ('public','private') then
  raise exception 'Invalid privacy setting';
 end if;
 if p_dugtong is not null and char_length(pg_catalog.btrim(p_dugtong)) not between 30 and 1200 then
  raise exception 'Dugtong must contain 30–1200 characters';
 end if;
 -- This call also holds the shared advisory lock until this transaction commits.
 v_cycle_id:=public.ensure_buklod_today_tip_cycle_v2();
 if p_cycle_id is distinct from v_cycle_id then
  raise exception 'Tip changed after 3 days without activity. Refresh and try again' using errcode='P0001';
 end if;
 insert into public.buklod_today_tip_engagement_v2(user_id,cycle_id)
  values(v_user,v_cycle_id) on conflict(user_id,cycle_id) do nothing;
 select * into v_existing from public.buklod_today_tip_engagement_v2
  where user_id=v_user and cycle_id=v_cycle_id for update;
 if p_dugtong is null and p_visibility is not null and v_existing.dugtong is null then
  raise exception 'Save a Dugtong before changing its privacy';
 end if;
 v_first_reaction:=p_reaction is not null and v_existing.reacted_at is null;
 v_first_dugtong:=p_dugtong is not null and v_existing.dugtong_at is null;
 v_changed_reaction:=p_reaction is not null and v_existing.reaction is distinct from p_reaction;
 v_changed_dugtong:=p_dugtong is not null and v_existing.dugtong is distinct from pg_catalog.btrim(p_dugtong);
 update public.buklod_today_tip_engagement_v2 set
  reaction=coalesce(p_reaction,reaction),
  reacted_at=case when v_first_reaction then now() else reacted_at end,
  dugtong=coalesce(pg_catalog.btrim(p_dugtong),dugtong),
  dugtong_at=case when v_first_dugtong then now() else dugtong_at end,
  visibility=coalesce(p_visibility,visibility),
  updated_at=now()
 where user_id=v_user and cycle_id=v_cycle_id;
 -- Only substantive engagement extends the card, never impressions or privacy toggles.
 if v_changed_reaction or v_changed_dugtong then
  update public.buklod_today_tip_cycles_v2
    set last_engagement_at=now() where id=v_cycle_id;
 end if;
 if v_first_reaction then
  v_ledger_id:=null;v_points:=null;
  insert into public.buklod_points_ledger(
    user_id,direction,points,activity_type,source_key,source_id,description)
   select v_user,'credit',r.base_points,r.activity_type,
     'weekly_tip:'||v_week::text||':reaction',null,
     'Verified BUKLOD Today reaction'
   from public.buklod_point_rules r
   where r.activity_type='weekly_tip_reaction' and r.is_active
    and r.base_points between 1 and coalesce(r.max_points_per_event,r.base_points)
    and r.base_points<=coalesce(r.weekly_cap_points,r.base_points)
   on conflict(user_id,source_key) do nothing returning id,points into v_ledger_id,v_points;
  if v_ledger_id is not null then v_awarded:=v_awarded+v_points;end if;
 end if;
 if v_first_dugtong then
  v_ledger_id:=null;v_points:=null;
  insert into public.buklod_points_ledger(
    user_id,direction,points,activity_type,source_key,source_id,description)
   select v_user,'credit',r.base_points,r.activity_type,
     'weekly_tip:'||v_week::text||':dugtong',null,
     'Verified BUKLOD Today reflection'
   from public.buklod_point_rules r
   where r.activity_type='weekly_tip_dugtong' and r.is_active
    and r.base_points between 1 and coalesce(r.max_points_per_event,r.base_points)
    and r.base_points<=coalesce(r.weekly_cap_points,r.base_points)
   on conflict(user_id,source_key) do nothing returning id,points into v_ledger_id,v_points;
  if v_ledger_id is not null then v_awarded:=v_awarded+v_points;end if;
 end if;
 return pg_catalog.jsonb_build_object('ok',true,'cycle_id',v_cycle_id,
   'dugtong_saved',p_dugtong is not null,'awarded_points',v_awarded,
   'points_pending_claim',v_awarded>0,
   'first_reaction',v_first_reaction,'first_dugtong',v_first_dugtong);
end;
$func$;
revoke all on function public.react_to_buklod_today_tip_v2(bigint,text,text,text) from public,anon,authenticated;
grant execute on function public.react_to_buklod_today_tip_v2(bigint,text,text,text) to authenticated;

-- Historic privacy controls remain available after the active tip changes.
create or replace function public.set_buklod_today_dugtong_visibility_v2(
 p_cycle_id bigint,p_visibility text)
returns boolean language plpgsql volatile security definer set search_path='' as $func$
declare v_user uuid := (select auth.uid());
begin
 if v_user is null then raise exception 'Sign in required' using errcode='42501';end if;
 if p_visibility not in ('public','private') or p_visibility is null then
  raise exception 'Invalid privacy setting';
 end if;
 update public.buklod_today_tip_engagement_v2
  set visibility=p_visibility,updated_at=now()
  where user_id=v_user and cycle_id=p_cycle_id and dugtong is not null;
 return found;
end;
$func$;
revoke all on function public.set_buklod_today_dugtong_visibility_v2(bigint,text) from public,anon,authenticated;
grant execute on function public.set_buklod_today_dugtong_visibility_v2(bigint,text) to authenticated;

create or replace function public.get_my_buklod_today_dugtong_history_v2()
returns jsonb language sql stable security definer set search_path='' as $func$
 select coalesce(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
   'cycle_id',q.cycle_id,'title',q.title,'dugtong',q.dugtong,
   'visibility',q.visibility,'date',q.dugtong_at) order by q.dugtong_at desc),'[]'::jsonb)
 from (
   select e.cycle_id,t.title,e.dugtong,e.visibility,e.dugtong_at
    from public.buklod_today_tip_engagement_v2 e
    join public.buklod_today_tip_cycles_v2 c on c.id=e.cycle_id
    join public.buklod_weekly_tips_v1 t on t.tip_index=c.tip_index
   where e.user_id=(select auth.uid()) and e.dugtong is not null
   order by e.dugtong_at desc limit 40
 ) q;
$func$;
revoke all on function public.get_my_buklod_today_dugtong_history_v2() from public,anon,authenticated;
grant execute on function public.get_my_buklod_today_dugtong_history_v2() to authenticated;
