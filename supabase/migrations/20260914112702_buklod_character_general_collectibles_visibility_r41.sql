create table if not exists private.buklod_character_public_events_v3 (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  metric_key text not null,
  source_table text not null,
  source_id text not null,
  occurred_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, metric_key, source_table, source_id)
);

create index if not exists buklod_character_public_events_v3_user_metric_time_idx
  on private.buklod_character_public_events_v3(user_id, metric_key, occurred_at desc);

create table if not exists private.buklod_character_public_metrics_v3 (
  user_id uuid not null references public.profiles(id) on delete cascade,
  metric_key text not null,
  metric_value bigint not null default 0 check (metric_value >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, metric_key)
);

create or replace function private.buklod_character_record_public_metric_v3(
  p_user_id uuid,
  p_metric_key text,
  p_source_table text,
  p_source_id text,
  p_occurred_at timestamptz default now(),
  p_metadata jsonb default '{}'::jsonb
) returns boolean
language plpgsql
security definer
set search_path=''
as $$
declare
  v_metric text := lower(btrim(coalesce(p_metric_key,'')));
  v_when timestamptz := coalesce(p_occurred_at,now());
  v_cap integer := 0;
  v_day date;
  v_week date;
  v_count integer := 0;
  v_event_id bigint;
  v_week_event_id bigint;
begin
  if p_user_id is null or nullif(btrim(coalesce(p_source_id,'')),'') is null then
    return false;
  end if;
  if v_metric not in ('character_public_post','character_public_comment','character_public_reaction','character_public_share') then
    return false;
  end if;

  v_cap := case v_metric
    when 'character_public_post' then 3
    when 'character_public_comment' then 8
    when 'character_public_reaction' then 12
    when 'character_public_share' then 5
    else 0
  end;
  v_day := (v_when at time zone 'Asia/Manila')::date;

  select count(*)::integer into v_count
  from private.buklod_character_public_events_v3 e
  where e.user_id=p_user_id
    and e.metric_key=v_metric
    and (e.occurred_at at time zone 'Asia/Manila')::date=v_day;

  if v_cap <= 0 or v_count >= v_cap then
    return false;
  end if;

  insert into private.buklod_character_public_events_v3(
    user_id,metric_key,source_table,source_id,occurred_at,metadata
  ) values (
    p_user_id,v_metric,btrim(p_source_table),btrim(p_source_id),v_when,coalesce(p_metadata,'{}'::jsonb)
  )
  on conflict do nothing
  returning id into v_event_id;

  if v_event_id is null then
    return false;
  end if;

  insert into private.buklod_character_public_metrics_v3(user_id,metric_key,metric_value)
  values(p_user_id,v_metric,1)
  on conflict(user_id,metric_key) do update
    set metric_value=private.buklod_character_public_metrics_v3.metric_value+1,
        updated_at=now();

  insert into private.buklod_character_public_metrics_v3(user_id,metric_key,metric_value)
  values(p_user_id,'character_public_actions',1)
  on conflict(user_id,metric_key) do update
    set metric_value=private.buklod_character_public_metrics_v3.metric_value+1,
        updated_at=now();

  v_week := date_trunc('week',v_when at time zone 'Asia/Manila')::date;
  insert into private.buklod_character_public_events_v3(
    user_id,metric_key,source_table,source_id,occurred_at,metadata
  ) values (
    p_user_id,'character_public_active_week','character_public_week',v_week::text,v_when,
    jsonb_build_object('week_start',v_week)
  )
  on conflict do nothing
  returning id into v_week_event_id;

  if v_week_event_id is not null then
    insert into private.buklod_character_public_metrics_v3(user_id,metric_key,metric_value)
    values(p_user_id,'character_public_active_weeks',1)
    on conflict(user_id,metric_key) do update
      set metric_value=private.buklod_character_public_metrics_v3.metric_value+1,
          updated_at=now();
  end if;

  perform private.buklod_eval_special_collectibles_v2(p_user_id,v_event_id);
  return true;
end;
$$;

create or replace function private.buklod_character_public_wall_metric_trigger_v3()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_post public.community_posts%rowtype;
  v_signal jsonb;
  v_abnormal jsonb;
  v_normalized text;
begin
  if tg_table_name='community_posts' then
    if new.user_id is null
       or coalesce(new.audience,'') <> 'public'
       or new.scope_id is not null
       or new.group_id is not null
       or new.church_id is not null
       or coalesce(new.is_hidden,false)
       or new.deleted_at is not null
       or coalesce(new.is_reel,false)
       or length(btrim(coalesce(new.body,''))) < 20 then
      return new;
    end if;
    v_signal := private.buklod_r36_meaningful_text_signal_v1(new.body);
    if not coalesce((v_signal->>'economic_meaningful_candidate')::boolean,false) then return new; end if;
    perform private.buklod_character_record_public_metric_v3(
      new.user_id,'character_public_post','community_posts',new.id::text,new.created_at,
      jsonb_build_object('audience','public','general_user',true)
    );

  elsif tg_table_name='comments' then
    if new.user_id is null or coalesce(new.is_hidden,false) or new.deleted_at is not null
       or length(btrim(coalesce(new.body,''))) < 15 then return new; end if;
    select * into v_post from public.community_posts where id=new.post_id;
    if v_post.id is null
       or coalesce(v_post.audience,'') <> 'public'
       or v_post.scope_id is not null or v_post.group_id is not null or v_post.church_id is not null
       or coalesce(v_post.is_hidden,false) or v_post.deleted_at is not null or coalesce(v_post.is_reel,false)
       or new.user_id=v_post.user_id then return new; end if;
    v_signal := private.buklod_r36_meaningful_text_signal_v1(new.body);
    if not coalesce((v_signal->>'economic_meaningful_candidate')::boolean,false) then return new; end if;
    v_normalized := coalesce(v_signal->>'normalized','');
    v_abnormal := private.buklod_r36_abnormal_activity_signal_v1(
      new.user_id,case when new.parent_id is null then 'comment' else 'reply' end,new.created_at,v_normalized,'r37_standard_social_points_v1'
    );
    if coalesce((v_abnormal->>'hold_economics')::boolean,true) then return new; end if;
    perform private.buklod_character_record_public_metric_v3(
      new.user_id,'character_public_comment','comments',new.id::text,new.created_at,
      jsonb_build_object('post_id',new.post_id,'general_user',true)
    );

  elsif tg_table_name='reactions' then
    if new.user_id is null then return new; end if;
    select * into v_post from public.community_posts where id=new.post_id;
    if v_post.id is null
       or coalesce(v_post.audience,'') <> 'public'
       or v_post.scope_id is not null or v_post.group_id is not null or v_post.church_id is not null
       or coalesce(v_post.is_hidden,false) or v_post.deleted_at is not null or coalesce(v_post.is_reel,false)
       or new.user_id=v_post.user_id then return new; end if;
    v_abnormal := private.buklod_r36_abnormal_activity_signal_v1(
      new.user_id,'reaction',new.created_at,null,'r37_standard_social_points_v1'
    );
    if coalesce((v_abnormal->>'hold_economics')::boolean,true) then return new; end if;
    perform private.buklod_character_record_public_metric_v3(
      new.user_id,'character_public_reaction','reactions',new.post_id::text||':'||new.user_id::text,new.created_at,
      jsonb_build_object('post_id',new.post_id,'general_user',true)
    );

  elsif tg_table_name='community_post_internal_shares' then
    if new.shared_by is null or coalesce(new.target_kind,'') <> 'PUBLIC_WALL' then return new; end if;
    select * into v_post from public.community_posts where id=new.source_post_id;
    if v_post.id is null
       or coalesce(v_post.audience,'') <> 'public'
       or v_post.scope_id is not null or v_post.group_id is not null or v_post.church_id is not null
       or coalesce(v_post.is_hidden,false) or v_post.deleted_at is not null or coalesce(v_post.is_reel,false)
       or new.shared_by=v_post.user_id then return new; end if;
    v_abnormal := private.buklod_r36_abnormal_activity_signal_v1(
      new.shared_by,'share',new.created_at,null,'r37_standard_social_points_v1'
    );
    if coalesce((v_abnormal->>'hold_economics')::boolean,true) then return new; end if;
    perform private.buklod_character_record_public_metric_v3(
      new.shared_by,'character_public_share','community_post_internal_shares',new.id::text,new.created_at,
      jsonb_build_object('source_post_id',new.source_post_id,'target_kind',new.target_kind,'general_user',true)
    );
  end if;
  return new;
end;
$$;

