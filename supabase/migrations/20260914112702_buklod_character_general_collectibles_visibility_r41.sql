update private.buklod_special_collectible_definitions_v2 d
set requirement = jsonb_build_object(
      'all',
      jsonb_build_array(
        jsonb_build_object('metric','character_public_actions','gte',(d.level_no * 4)::bigint),
        case (d.level_no % 4)
          when 1 then jsonb_build_object('metric','character_public_post','gte',greatest(1,ceil(d.level_no::numeric/2)::bigint))
          when 2 then jsonb_build_object('metric','character_public_comment','gte',greatest(2,d.level_no::bigint))
          when 3 then jsonb_build_object('metric','character_public_reaction','gte',greatest(3,(d.level_no * 2)::bigint))
          else jsonb_build_object('metric','character_public_share','gte',greatest(1,ceil(d.level_no::numeric/2)::bigint))
        end
      ) || case when d.level_no >= 9 then
        jsonb_build_array(jsonb_build_object('metric','character_public_active_weeks','gte',greatest(2,ceil((d.level_no-5)::numeric/3)::bigint)))
      else '[]'::jsonb end
    ),
    reward_scope='GENERAL',
    scope_review_required=false,
    updated_at=now()
where d.is_active=true;

create or replace function private.buklod_eval_special_collectibles_v2(p_user_id uuid, p_trigger_event_id bigint default null)
returns integer
language plpgsql
security definer
set search_path=''
as $$
declare
  v_count integer:=0;
  v_points bigint:=0;
  v_rank integer:=1;
  r record;
begin
  if p_user_id is null then return 0; end if;

  select coalesce(b.lifetime_points,0) into v_points
  from public.buklod_user_points_balances b
  where b.user_id=p_user_id;
  if not found then v_points:=0; end if;

  select coalesce(max(rl.rank_order),1) into v_rank
  from public.buklod_rank_levels rl
  where rl.is_active=true and rl.min_points<=greatest(v_points,0);

  for r in
    select d.*
    from private.buklod_special_collectible_definitions_v2 d
    join private.buklod_special_character_series_registry s on s.character_id=d.character_id and s.is_active=true
    where d.is_active=true
      and s.unlock_rank_order<=v_rank
      and not exists(
        select 1 from private.buklod_special_collectible_awards_v2 a
        where a.user_id=p_user_id and a.collectible_id=d.collectible_id
      )
      and not exists(
        select 1
        from jsonb_array_elements(coalesce(d.requirement->'all','[]'::jsonb)) req
        where coalesce((
          select m.metric_value
          from private.buklod_character_public_metrics_v3 m
          where m.user_id=p_user_id and m.metric_key=req->>'metric'
        ),0) < coalesce((req->>'gte')::bigint,0)
      )
  loop
    insert into private.buklod_special_collectible_awards_v2(
      user_id,collectible_id,character_id,level_no,trigger_event_id,requirement_snapshot
    ) values (
      p_user_id,r.collectible_id,r.character_id,r.level_no,p_trigger_event_id,r.requirement
    ) on conflict do nothing;

    if found then
      v_count:=v_count+1;
      insert into public.notifications(user_id,title,body,kind,data)
      values(
        p_user_id,
        case when r.is_secret then '✨ Secret Collectible Discovered!' else '🏆 Collectible Earned!' end,
        r.collectible_name||' • '||upper(r.character_id)||' • Level '||r.level_no,
        'character_collectible',
        jsonb_build_object(
          'character_id',r.character_id,'level_no',r.level_no,'collectible_id',r.collectible_id,
          'collectible_name',r.collectible_name,'badge_name',r.badge_name,'secret',r.is_secret
        )
      );
    end if;
  end loop;
  return v_count;
end;
$$;

create or replace function public.get_my_buklod_special_character_state_v2()
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_points bigint := 0;
  v_rank integer := 1;
  v_active_special text;
  v_items jsonb;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  perform private.buklod_reconcile_special_character_unlocks_v2(v_uid);

  select coalesce(lifetime_points,0) into v_points
  from public.buklod_user_points_balances where user_id=v_uid;
  if not found then v_points:=0; end if;

  select coalesce(max(rank_order),1) into v_rank
  from public.buklod_rank_levels where is_active=true and min_points<=greatest(v_points,0);

  select s.character_id into v_active_special
  from private.buklod_special_character_selection s
  where s.user_id=v_uid;

  select coalesce(jsonb_agg(jsonb_build_object(
    'character_id',c.character_id,
    'display_name',case when c.character_id='jawo' then 'JAVVO' else c.display_name end,
    'series_no',c.series_no,
    'unlock_rank_order',c.unlock_rank_order,
    'domain_key',c.domain_key,
    'unlocked',true,
    'level1_preview_allowed',true,
    'current_level',private.buklod_special_current_level_v2(v_uid,c.character_id),
    'level_count',20,
    'stage_titles',(select sc.stage_titles from private.buklod_special_character_catalog sc where sc.character_id=c.character_id limit 1),
    'active',(v_active_special=c.character_id)
  ) order by c.reveal_order),'[]'::jsonb) into v_items
  from private.buklod_special_character_series_registry c
  where c.is_active=true and c.unlock_rank_order<=v_rank;

  return jsonb_build_object(
    'series_no',1,
    'circle_rank_order',v_rank,
    'visibility_rule','UNLOCKED_ONLY_NO_LOCKED_IDENTITY',
    'active_special_character_id',v_active_special,
    'characters',v_items
  );
end;
$$;

create or replace function public.get_my_buklod_special_collectibles_v2(p_character_id text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_character text := lower(btrim(coalesce(p_character_id,'')));
  v_unlocked boolean:=false;
  v_current integer:=1;
  v_items jsonb;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  perform private.buklod_reconcile_special_character_unlocks_v2(v_uid);

  select exists(
    select 1 from private.buklod_special_character_user_state s
    where s.user_id=v_uid and s.character_id=v_character and s.unlocked_at is not null
  ) into v_unlocked;

  if not v_unlocked then
    raise exception 'Special Character is not unlocked';
  end if;

  v_current:=private.buklod_special_current_level_v2(v_uid,v_character);
  perform private.buklod_eval_special_collectibles_v2(v_uid,null);

  select coalesce(jsonb_agg(jsonb_build_object(
    'level_no',d.level_no,
    'collectible_id',d.collectible_id,
    'collectible_name',case when d.is_secret and a.earned_at is null then '???' else d.collectible_name end,
    'badge_name',case when d.is_secret and a.earned_at is null then '???' else d.badge_name end,
    'difficulty_tier',d.difficulty_tier,
    'secret',d.is_secret,
    'earned',(a.earned_at is not null),
    'earned_at',a.earned_at,
    'earned_early',(a.earned_at is not null and d.level_no>v_current),
    'level_viewable',(d.level_no<=v_current),
    'requirement',case when d.is_secret and a.earned_at is null then null else d.requirement end
  ) order by d.level_no),'[]'::jsonb) into v_items
  from private.buklod_special_collectible_definitions_v2 d
  left join private.buklod_special_collectible_awards_v2 a
    on a.user_id=v_uid and a.collectible_id=d.collectible_id
  where d.character_id=v_character and d.is_active=true;

  return jsonb_build_object(
    'character_id',v_character,
    'unlocked',true,
    'current_level',v_current,
    'level1_always_viewable',false,
    'collectible_metric_scope','GENERAL_PUBLIC_WALL_ONLY',
    'collectibles',v_items
  );
end;
$$;

