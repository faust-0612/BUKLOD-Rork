-- BUKLOD Living Community R1: global KL and important occasion notifications.
-- No schedules are activated here. Use the separate release activation script.
begin;

create table if not exists public.buklod_living_global_events (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  event_kind text not null check (event_kind in ('kl_release','holiday')),
  title text not null,
  body text not null,
  route text not null,
  faith_sensitive boolean not null default false,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists buklod_living_global_recent_idx
  on public.buklod_living_global_events(occurred_at desc);

create table if not exists public.buklod_living_global_deliveries (
  event_id bigint not null references public.buklod_living_global_events(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(event_id,user_id)
);
alter table public.buklod_living_global_events enable row level security;
alter table public.buklod_living_global_deliveries enable row level security;
revoke all on public.buklod_living_global_events from public,anon,authenticated;
revoke all on public.buklod_living_global_deliveries from public,anon,authenticated;

-- Only server scheduler can create canonical release events. The newest released
-- chapter in the last seven days wins; no leaked draft or future scheduled chapter.
create or replace function public.buklod_living_generate_global_events()
returns integer language plpgsql security definer set search_path='' as $$
declare
  v_day date := (now() at time zone 'Asia/Manila')::date;
  v_mmdd text := to_char((now() at time zone 'Asia/Manila'), 'MM-DD');
  v_title text;
  v_body text;
  v_kind text;
  v_faith boolean := false;
  v_added integer := 0;
  v_count integer;
begin
  insert into public.buklod_living_global_events
    (dedupe_key,event_kind,title,body,route,faith_sensitive,occurred_at)
  select
    'kl:'||e.id::text,
    'kl_release',
    'Bagong kabanata sa Kabihasnang Ligaw! 📖',
    'Kabanata '||e.episode_number::text||': '||left(e.title,110)||' — basahin sa BUKLOD.',
    '/kabihasnang-ligaw',
    false,
    e.release_at
  from public.kl_episodes e
  where e.status='approved' and e.release_at is not null
    and e.release_at <= now()
    and e.release_at >= now()-interval '7 days'
    and e.episode_number > 0
  order by e.release_at desc
  limit 1
  on conflict(dedupe_key) do nothing;
  get diagnostics v_count = row_count;
  v_added := v_added + v_count;

  -- Stable Philippine calendar dates only; do not guess movable holidays.
  case v_mmdd
    when '01-01' then
      v_title := 'Manigong Bagong Taon! ✨';
      v_body := 'Mula sa BUKLOD, isang bagong simula ng pagkakaisa at pag-asa.';
    when '06-12' then
      v_title := 'Maligayang Araw ng Kalayaan! 🇵🇭';
      v_body := 'Mula sa BUKLOD, ipagdiwang natin ang kalayaan at paglilingkod.';
    when '11-30' then
      v_title := 'Araw ni Bonifacio 🇵🇭';
      v_body := 'Mula sa BUKLOD, alalahanin natin ang tapang at kabayanihan.';
    when '12-25' then
      v_title := 'Maligayang Pasko mula sa BUKLOD! 🎄';
      v_body := 'Pagmamahalan at pag-asa para sa inyong tahanan.';
      v_faith := true;
    when '12-30' then
      v_title := 'Araw ni Rizal 🇵🇭';
      v_body := 'Mula sa BUKLOD, alalahanin natin ang paglilingkod sa bayan.';
    else
      v_title := null;
  end case;

  if v_title is not null then
    insert into public.buklod_living_global_events
      (dedupe_key,event_kind,title,body,route,faith_sensitive,occurred_at)
    values ('occasion:'||v_day::text,'holiday',v_title,v_body,'/hub',v_faith,now())
    on conflict(dedupe_key) do nothing;
    get diagnostics v_count = row_count;
    v_added := v_added + v_count;
  end if;

  delete from public.buklod_living_global_events
    where occurred_at < now()-interval '14 days';
  return v_added;
end
$$;
revoke all on function public.buklod_living_generate_global_events()
  from public,anon,authenticated;

-- At most 120 user deliveries per invocation, idempotent even if jobs overlap.
-- Announcement opt-out and faith opt-out are enforced at SQL level.
create or replace function public.buklod_living_dispatch_global_notifications(
  p_batch integer default 100
)
returns integer language plpgsql security definer set search_path='' as $$
declare
  v_delivered integer := 0;
begin
  with eligible as (
    select e.*
    from public.buklod_living_global_events e
    where e.occurred_at between now()-interval '7 days' and now()
    order by e.occurred_at desc
    limit 30
  ), candidate as (
    select e.id as event_id, p.id as user_id
    from eligible e
    join public.profiles p on p.is_active is true
    left join public.notification_preferences np on np.user_id=p.id
    left join public.buklod_user_preferences up on up.user_id=p.id
    left join public.buklod_living_global_deliveries already
      on already.event_id=e.id and already.user_id=p.id
    where already.event_id is null
      and coalesce(np.announcements,true) is true
      and (e.faith_sensitive is false or coalesce(up.show_faith_content,false) is true)
    order by e.occurred_at desc,p.id
    limit least(greatest(coalesce(p_batch,100),1),120)
  ), delivered as (
    insert into public.buklod_living_global_deliveries(event_id,user_id)
    select event_id,user_id from candidate
    on conflict do nothing
    returning event_id,user_id
  ), created as (
    insert into public.notifications(user_id,title,body,kind,data)
    select d.user_id,e.title,e.body,'announcement_living_community',
      jsonb_build_object('route',e.route,'event_id',e.id,'event_kind',e.event_kind)
    from delivered d
    join public.buklod_living_global_events e on e.id=d.event_id
    returning id
  )
  select count(*)::integer into v_delivered from created;
  return coalesce(v_delivered,0);
end
$$;
revoke all on function public.buklod_living_dispatch_global_notifications(integer)
  from public,anon,authenticated;

commit;
