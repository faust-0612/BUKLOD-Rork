-- BUKLOD Living Community R1.
-- Canonical audiences: follower graph and active CLUSTER/ORGANIZATION memberships.
-- No legacy church_id, church directory, or unscoped personal-data broadcast.
-- Birthdays require explicit opt-in; welcome is on by default and can be disabled.
begin;

create table if not exists public.buklod_living_celebration_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  welcome_to_network boolean not null default true,
  birthday_to_network boolean not null default false,
  updated_at timestamptz not null default now()
);
alter table public.buklod_living_celebration_preferences enable row level security;
revoke all on public.buklod_living_celebration_preferences from public, anon, authenticated;
grant select, insert, update on public.buklod_living_celebration_preferences to authenticated;

create policy buklod_living_own_select on public.buklod_living_celebration_preferences
  for select to authenticated using (user_id = (select auth.uid()));
create policy buklod_living_own_insert on public.buklod_living_celebration_preferences
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy buklod_living_own_update on public.buklod_living_celebration_preferences
  for update to authenticated using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Internal-only event log and exact-once recipient ledger.
create table if not exists public.buklod_living_network_events (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  event_kind text not null check (event_kind in ('new_member','birthday')),
  subject_user_id uuid not null references auth.users(id) on delete cascade,
  scope_id uuid references public.buklod_scopes(id) on delete cascade,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists buklod_living_events_recent_idx
  on public.buklod_living_network_events (occurred_at desc);

create table if not exists public.buklod_living_event_deliveries (
  event_id bigint not null references public.buklod_living_network_events(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(event_id,recipient_id)
);
alter table public.buklod_living_network_events enable row level security;
alter table public.buklod_living_event_deliveries enable row level security;
revoke all on public.buklod_living_network_events from public, anon, authenticated;
revoke all on public.buklod_living_event_deliveries from public, anon, authenticated;

-- No fan-out inside the membership transaction: the trigger only appends one event.
create or replace function public.buklod_living_on_scope_activation()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_scope_type text;
begin
  if new.membership_status <> 'ACTIVE'
    or (tg_op = 'UPDATE' and old.membership_status = 'ACTIVE') then
    return new;
  end if;

  select s.scope_type into v_scope_type from public.buklod_scopes s
  where s.id = new.scope_id and s.status = 'ACTIVE';
  if v_scope_type not in ('CLUSTER','ORGANIZATION') then return new; end if;

  if not exists (
    select 1 from public.profiles p
    left join public.buklod_living_celebration_preferences cp on cp.user_id=p.id
    left join public.buklod_user_preferences up on up.user_id=p.id
    where p.id=new.user_id and p.is_active is true
      and coalesce(cp.welcome_to_network,true) is true
      and coalesce(up.profile_locked,false) is false
  ) then return new; end if;

  insert into public.buklod_living_network_events
    (dedupe_key,event_kind,subject_user_id,scope_id,occurred_at)
  values ('join:'||new.id::text,'new_member',new.user_id,new.scope_id,
    coalesce(new.joined_at,now()))
  on conflict(dedupe_key) do nothing;
  return new;
exception when others then
  -- Celebrations must never block an actual approved membership.
  raise warning 'BUKLOD welcome event skipped: %',sqlerrm;
  return new;
end
$$;

drop trigger if exists buklod_living_scope_activation_r1 on public.buklod_scope_memberships;
create trigger buklod_living_scope_activation_r1
  after insert or update of membership_status on public.buklod_scope_memberships
  for each row execute function public.buklod_living_on_scope_activation();

-- Server-side publication includes only events the requester is entitled to see.
-- Never returns date of birth, year of birth, mobile, email, or private profiles.
create or replace function public.buklod_living_network_celebrations()
returns table (
  event_id bigint,
  event_kind text,
  subject_user_id uuid,
  subject_name text,
  scope_label text,
  occurred_at timestamptz
)
language sql stable security definer set search_path='' as $$
  select
    e.id,
    e.event_kind,
    e.subject_user_id,
    left(coalesce(nullif(trim(p.full_name),''),'BUKLOD member'),80),
    case when e.scope_id is not null and exists (
      select 1 from public.buklod_scope_memberships vm
      where vm.user_id=(select auth.uid()) and vm.scope_id=e.scope_id
        and vm.membership_status='ACTIVE'
    ) then s.name else null end,
    e.occurred_at
  from public.buklod_living_network_events e
  join public.profiles p on p.id=e.subject_user_id and p.is_active is true
  left join public.buklod_scopes s on s.id=e.scope_id and s.status='ACTIVE'
  left join public.buklod_living_celebration_preferences cp
    on cp.user_id=e.subject_user_id
  left join public.buklod_user_preferences up
    on up.user_id=e.subject_user_id
  where (select auth.uid()) is not null
    and coalesce(up.profile_locked,false) is false
    and e.subject_user_id <> (select auth.uid())
    and e.occurred_at >= now()-interval '7 days'
    and e.occurred_at <= now()
    and case when e.event_kind='birthday'
      then coalesce(cp.birthday_to_network,false)
      else coalesce(cp.welcome_to_network,true) end
    and (
      exists (
        select 1 from public.buklod_user_follows f
        where f.follower_id=(select auth.uid())
          and f.followed_user_id=e.subject_user_id
      )
      or exists (
        select 1 from public.buklod_scope_memberships vm
        join public.buklod_scope_memberships sm
          on sm.scope_id=vm.scope_id
         and sm.user_id=e.subject_user_id
         and sm.membership_status='ACTIVE'
        join public.buklod_scopes shared on shared.id=vm.scope_id
        where vm.user_id=(select auth.uid())
          and vm.membership_status='ACTIVE'
          and shared.scope_type in ('CLUSTER','ORGANIZATION')
          and shared.status='ACTIVE'
          and (e.event_kind='birthday' or vm.scope_id=e.scope_id)
      )
    )
  order by e.occurred_at desc
  limit 12
$$;
revoke all on function public.buklod_living_network_celebrations() from public,anon;
grant execute on function public.buklod_living_network_celebrations() to authenticated;

-- Generate birthday events once per Philippine calendar day; consent is mandatory.
create or replace function public.buklod_living_generate_birthdays()
returns integer language plpgsql security definer set search_path='' as $$
declare inserted_count integer;
begin
  insert into public.buklod_living_network_events
    (dedupe_key,event_kind,subject_user_id,occurred_at)
  select
    'birthday:'||p.id::text||':'||(now() at time zone 'Asia/Manila')::date::text,
    'birthday',p.id,now()
  from public.profiles p
  join public.buklod_living_celebration_preferences cp
    on cp.user_id=p.id and cp.birthday_to_network is true
  left join public.buklod_user_preferences up on up.user_id=p.id
  where p.is_active is true and coalesce(up.profile_locked,false) is false
    and p.birth_date is not null
    and extract(month from p.birth_date)=extract(month from now() at time zone 'Asia/Manila')
    and extract(day from p.birth_date)=extract(day from now() at time zone 'Asia/Manila')
  on conflict(dedupe_key) do nothing;
  get diagnostics inserted_count = row_count;

  delete from public.buklod_living_network_events
  where occurred_at < now()-interval '14 days';
  return inserted_count;
end
$$;
revoke all on function public.buklod_living_generate_birthdays() from public,anon,authenticated;

-- Set-based, bounded notification fan-out, paced by scheduler.
-- Notification delivery respects the existing community_activity preference.
create or replace function public.buklod_living_dispatch_notifications(p_batch integer default 80)
returns integer language plpgsql security definer set search_path='' as $$
declare delivered_count integer;
begin
  with eligible_events as (
    select e.*
    from public.buklod_living_network_events e
    join public.profiles p on p.id=e.subject_user_id and p.is_active is true
    left join public.buklod_living_celebration_preferences cp
      on cp.user_id=e.subject_user_id
    left join public.buklod_user_preferences up on up.user_id=e.subject_user_id
    where e.occurred_at between now()-interval '7 days' and now()
      and coalesce(up.profile_locked,false) is false
      and case when e.event_kind='birthday'
        then coalesce(cp.birthday_to_network,false)
        else coalesce(cp.welcome_to_network,true) end
    order by e.occurred_at asc limit 400
  ), recipients as (
    select e.id as event_id, f.follower_id as recipient_id
    from eligible_events e
    join public.buklod_user_follows f on f.followed_user_id=e.subject_user_id
    union
    select e.id, vm.user_id
    from eligible_events e
    join public.buklod_scope_memberships sm
      on sm.user_id=e.subject_user_id and sm.membership_status='ACTIVE'
    join public.buklod_scope_memberships vm
      on vm.scope_id=sm.scope_id and vm.membership_status='ACTIVE'
    join public.buklod_scopes scope on scope.id=vm.scope_id
      and scope.scope_type in ('CLUSTER','ORGANIZATION') and scope.status='ACTIVE'
    where e.event_kind='birthday' or e.scope_id=vm.scope_id
  ), candidate as (
    select r.event_id,r.recipient_id
    from recipients r
    join eligible_events e on e.id=r.event_id
    join public.profiles rp on rp.id=r.recipient_id and rp.is_active is true
    left join public.notification_preferences np on np.user_id=r.recipient_id
    left join public.buklod_living_event_deliveries existing
      on existing.event_id=r.event_id and existing.recipient_id=r.recipient_id
    where r.recipient_id<>e.subject_user_id
      and coalesce(np.community_activity,true)
      and existing.event_id is null
    order by r.event_id,r.recipient_id
    limit least(greatest(coalesce(p_batch,80),1),200)
  ), delivered as (
    insert into public.buklod_living_event_deliveries(event_id,recipient_id)
    select event_id,recipient_id from candidate
    on conflict do nothing
    returning event_id,recipient_id
  ), notifications_created as (
    insert into public.notifications(user_id,title,body,kind,data)
    select d.recipient_id,
      case when e.event_kind='birthday'
        then '🎉 BUKLOD: May birthday sa iyong community!'
        else '💚 BUKLOD: May bagong kasamang pwedeng batiin!' end,
      case when e.event_kind='birthday'
        then left(coalesce(nullif(trim(p.full_name),''),'BUKLOD member'),80)||' ay may kaarawan ngayon. Batiin natin!'
        else 'I-welcome natin si '||left(coalesce(nullif(trim(p.full_name),''),'BUKLOD member'),80)||' sa BUKLOD!' end,
      'community_living_celebration',
      jsonb_build_object('route','/buklod','event_id',e.id,
        'event_kind',e.event_kind,'subject_user_id',e.subject_user_id)
    from delivered d
    join public.buklod_living_network_events e on e.id=d.event_id
    join public.profiles p on p.id=e.subject_user_id
    returning id
  )
  select count(*)::integer into delivered_count from notifications_created;
  return coalesce(delivered_count,0);
end
$$;
revoke all on function public.buklod_living_dispatch_notifications(integer) from public,anon,authenticated;

-- Scheduled jobs only after a release gate applies this migration.
-- Database uses UTC: 16:05 UTC is 00:05 in Manila the next day.
do $$
begin
  if exists(select 1 from pg_extension where extname='pg_cron') then
    perform cron.schedule('buklod-living-birthdays-r1',
      '5 16 * * *',
      'select public.buklod_living_generate_birthdays()');
    perform cron.schedule('buklod-living-notifications-r1',
      '* * * * *',
      'select public.buklod_living_dispatch_notifications(80)');
  end if;
end
$$;
commit;
