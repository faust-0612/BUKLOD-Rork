-- Non-destructive verification of IGPAT retirement.
-- Run after migration 20261111151816. All fixture writes are TEMP and rolled back.
BEGIN;
DO $assert$
DECLARE
  protected_count integer;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgrelid = 'public.community_posts'::regclass
      AND tgname = 'trg_buklod_retired_igpat_write'
      AND tgenabled = 'O'
  ) THEN
    RAISE EXCEPTION 'IGPAT write-block trigger absent or disabled';
  END IF;

  SELECT count(*) INTO protected_count
  FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
  WHERE n.nspname='public'
    AND (p.proname LIKE 'create_buklod_reel%'
      OR p.proname LIKE 'get_buklod_igpat_feed%'
      OR p.proname IN ('get_buklod_reels_v1','get_my_active_igpat_groups_v1'))
    AND NOT has_function_privilege('authenticated',p.oid,'EXECUTE')
    AND NOT has_function_privilege('anon',p.oid,'EXECUTE');

  IF protected_count <> 8 THEN
    RAISE EXCEPTION 'Expected eight retired client RPCs without execute grants; found %',protected_count;
  END IF;
END;
$assert$;

CREATE TEMP TABLE buklod_igpat_retire_probe (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  is_reel boolean DEFAULT false
) ON COMMIT DROP;

CREATE TRIGGER probe_igpat_retirement
BEFORE INSERT OR UPDATE OF is_reel ON buklod_igpat_retire_probe
FOR EACH ROW EXECUTE FUNCTION private.buklod_reject_retired_igpat_v1();

DO $test$
DECLARE
  count_normal integer;
  expected text := 'BUKLOD IGPAT has been retired.';
BEGIN
  BEGIN
    INSERT INTO buklod_igpat_retire_probe (is_reel) VALUES (true);
    RAISE EXCEPTION 'Unexpected success: retired IGPAT insert was accepted';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF position(expected in SQLERRM) = 0 THEN
      RAISE EXCEPTION 'Wrong rejection on IGPAT insert: %', SQLERRM;
    END IF;
  END;

  INSERT INTO buklod_igpat_retire_probe (is_reel) VALUES (false);
  INSERT INTO buklod_igpat_retire_probe DEFAULT VALUES;

  BEGIN
    UPDATE buklod_igpat_retire_probe SET is_reel = true WHERE is_reel = false;
    RAISE EXCEPTION 'Unexpected success: normal post converted to IGPAT';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF position(expected in SQLERRM) = 0 THEN
      RAISE EXCEPTION 'Wrong rejection on conversion: %', SQLERRM;
    END IF;
  END;

  SELECT count(*) INTO count_normal FROM buklod_igpat_retire_probe WHERE is_reel=false;
  IF count_normal <> 2 THEN
    RAISE EXCEPTION 'Normal posts were affected: expected 2, got %',count_normal;
  END IF;
END;
$test$;

ROLLBACK;
