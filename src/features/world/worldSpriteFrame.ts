/**
 * Presentation-only PNG frame resolver for permanent World construction.
 * No client-rendered image is proof of ownership, earned BP, or a build receipt.
 * `level` is the highest COMPLETED tier; `stage` is work on tier level + 1.
 */
import type { WorldDevelopmentTrack } from './worldDevelopmentCatalog';

export type WorldSpriteTrack = WorldDevelopmentTrack | 'business';
export type WorldSpriteProgress = Readonly<{
  worldId: string;
  track: WorldSpriteTrack;
  level: number;
  stage: number;
  revision: number;
  origin: 'authoritative_server' | 'local_design_preview';
  /** Receipt validated by the backend, never generated by the UI. */
  receiptId: string | null;
}>;
export type WorldSpriteFrame = Readonly<{
  worldId: string;
  revision: number;
  status: 'verified' | 'preview' | 'unavailable';
  track: WorldSpriteTrack | null;
  completedLevel: number;
  buildingLevel: number | null;
  stage: number;
  frameKey: string | null;
  fallbackFrameKey: string | null;
  label: string;
}>;

const PREFIX: Readonly<Record<WorldSpriteTrack,string>> = {
  personal_lot:'lot', house:'hou', farm:'far', cluster:'com',
  organization:'org', business:'biz',
};
const unavailable = (p: WorldSpriteProgress): WorldSpriteFrame => ({
  worldId:typeof p?.worldId==='string'?p.worldId:'', revision:Number.isSafeInteger(p?.revision)?p.revision:0,
  status:'unavailable', track:null, completedLevel:0, buildingLevel:null,
  stage:0, frameKey:null, fallbackFrameKey:null,
  label:'Construction progress unavailable',
});
const levelKey = (prefix:string, level:number) => `${prefix}_l${String(level).padStart(2,'0')}`;

export function resolveWorldSpriteFrame(p:WorldSpriteProgress):WorldSpriteFrame {
  if(!p || typeof p.worldId!=='string' || !p.worldId.trim() ||
    !Object.prototype.hasOwnProperty.call(PREFIX,p.track) ||
    !Number.isSafeInteger(p.level) || p.level<0 || p.level>10 ||
    !Number.isSafeInteger(p.stage) || p.stage<0 || p.stage>5 ||
    !Number.isSafeInteger(p.revision) || p.revision<0 ||
    (p.level===10 && p.stage>0)) return unavailable(p);
  const verified=p.origin==='authoritative_server' && typeof p.receiptId==='string' && p.receiptId.trim().length>0;
  const preview=p.origin==='local_design_preview';
  if(!verified && !preview) return unavailable(p);
  const prefix=PREFIX[p.track];
  const completed=p.level>0?levelKey(prefix,p.level):null;
  const building=p.stage>0?p.level+1:null;
  return {
    worldId:p.worldId,revision:p.revision,
    status:verified?'verified':'preview',track:p.track,
    completedLevel:p.level,buildingLevel:building,stage:p.stage,
    frameKey:building?`${levelKey(prefix,building)}_s${String(p.stage).padStart(2,'0')}`:completed,
    fallbackFrameKey:building?completed:null,
    label:building?`Level ${building} · construction stage ${p.stage} of 5`:
      p.level===0?'Vacant lot · not started':`Level ${p.level} · completed`,
  };
}

/** Reject stale / conflicting same-revision data; switching world clears the old image. */
export function mayShowWorldSpriteFrame(previous:WorldSpriteFrame,next:WorldSpriteFrame):boolean {
  if(previous.worldId!==next.worldId || previous.track!==next.track) return true;
  if(next.revision<previous.revision) return false;
  if(next.revision===previous.revision &&
    (next.frameKey!==previous.frameKey || next.status!==previous.status)) return false;
  // Local, unverified preview may not replace verified progress for the same world.
  if(previous.status==='verified' && next.status==='preview') return false;
  return true;
}

/** Pure asset lookup: missing stage art never pretends the tier is complete. */
export function chooseWorldSpriteAsset<T>(
  frame:WorldSpriteFrame,
  registry:Readonly<Partial<Record<string,T>>>,
):{source:T|null;artKey:string|null;isFallback:boolean} {
  if(frame.status==='unavailable') return {source:null,artKey:null,isFallback:false};
  if(frame.frameKey && registry[frame.frameKey]!=null)
    return {source:registry[frame.frameKey]!,artKey:frame.frameKey,isFallback:false};
  if(frame.fallbackFrameKey && registry[frame.fallbackFrameKey]!=null)
    return {source:registry[frame.fallbackFrameKey]!,artKey:frame.fallbackFrameKey,isFallback:true};
  return {source:null,artKey:null,isFallback:false};
}
