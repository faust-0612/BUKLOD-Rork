export function getWordBibleReaderTarget(reference: string | null | undefined) {
  if (typeof reference !== 'string') return null;
  const clean = reference.trim().replace(/\s+/g, ' ');
  if (!clean) return null;
  const lower = clean.toLowerCase();
  const book = BIBLE_BOOK_NUMBERS.find(([name]) => lower.startsWith(`${name} `));
  if (!book) return null;
  const rest = clean.slice(book[0].length).trim();
  const match = rest.match(/^(\d{1,3})(?::(\d{1,3}))?(?:\s*[-–—]\s*\d{1,3}(?::\d{1,3})?)?$/);
  if (!match) return null;
  const chapterNo = Number(match[1]);
  const verseNo = match[2] ? Number(match[2]) : null;
  if (chapterNo < 1 || chapterNo > 150 || (verseNo !== null && (verseNo < 1 || verseNo > 176))) return null;
  return { bookNo: book[1], chapterNo, verseNo };
}
