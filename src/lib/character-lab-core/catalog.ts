const BY_ID: Record<string, CatalogItem> = CATALOG.reduce<Record<string, CatalogItem>>(
  (acc, item) => {
    acc[item.id] = item;
    return acc;
  },
  {},
);

export function getItem(id: string | null): CatalogItem | null {
  if (!id) return null;
  return BY_ID[id] ?? null;
}

/** Items offered for a slot, filtered to the selected body. */
export function itemsForSlot(slot: SlotId, body: BodyId): CatalogItem[] {
  return CATALOG.filter(
    (item) => item.slot === slot && (!item.bodies || item.bodies.includes(body)),
  );
}

/** Resolves the manifest asset key for an item on a given body. */
export function assetKeyFor(item: CatalogItem, body: BodyId): string | null {
  if (!item.asset) return null;
  return item.asset[body] ?? item.asset.shared ?? null;
}

