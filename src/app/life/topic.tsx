const LIFE_TOPIC_KEYS =
  new Set<BuklodLifeTopicKey>([
    'hope',
    'peace',
    'purpose',
    'forgiveness',
    'strength',
    'new-start',
    'questions',
    'jesus',
    'help',
  ]);


function safeTopic(
  value: unknown,
): BuklodLifeTopicKey {
  const key =
    String(
      value ?? ''
    ) as BuklodLifeTopicKey;

  return LIFE_TOPIC_KEYS.has(
    key
  )
    ? key
    : 'hope';
}


