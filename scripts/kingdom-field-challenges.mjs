export function buildFieldChallenge(id,raw){
 if(ADVANCED_FIELD_CHALLENGES[id])return JSON.parse(JSON.stringify(ADVANCED_FIELD_CHALLENGES[id]));
 if(!raw)throw Error("Missing field challenge "+id);
 const [type,prompt,items,answer,limit]=raw;let d={type,prompt};
 if(type==="budget"){d={...d,items,goal:answer,limit};const combinations=[];for(let mask=1;mask<1<<items.length;mask++){let s=0,n=0;for(let i=0;i<items.length;i++)if(mask>>i&1){s+=items[i];n++;}if(s===answer&&n===limit)combinations.push(mask)}if(!combinations.length)throw Error("Unsolvable "+id);}
 else if(type==="route"){d={...d,items:Array.from({length:9},(_,i)=>i===0?"Start":i===8?"Goal":answer.includes(i)?"Blocked":"Path"),path:items};if(items[0]!==0||items.at(-1)!==8||items.some((x,i)=>i>0&&Math.abs(x%3-items[i-1]%3)+Math.abs(Math.floor(x/3)-Math.floor(items[i-1]/3))!==1))throw Error("Broken path "+id);}
 else if(type==="pair"){d={...d,items};if(items.some(x=>items.filter(y=>y===x).length!==2))throw Error("Bad pairs "+id);}
 else {d={...d,items,answer};if(type==="select"?!Number.isInteger(answer)||answer<0||answer>=items.length:!Array.isArray(answer)||answer.some(x=>x<0||x>=items.length))throw Error("Bad answer "+id);}
 return d;
}
