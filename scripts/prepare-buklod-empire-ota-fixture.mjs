/** Ephemeral test-only trust root; never enters APK or production. */
import {generateKeyPairSync,createHash,sign} from 'node:crypto';
import {mkdirSync,writeFileSync,readFileSync,copyFileSync,rmSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import assert from 'node:assert/strict';
const dir=path.resolve(process.argv[2]);
mkdirSync(path.join(dir,'scripts'),{recursive:true});
mkdirSync(path.join(dir,'data'),{recursive:true});
mkdirSync(path.join(dir,'empire-ota'),{recursive:true});
mkdirSync(path.join(dir,'fixtures'),{recursive:true});
copyFileSync('apps/buklod-empire/game/empire_ota.gd',path.join(dir,'scripts/empire_ota.gd'));
copyFileSync('apps/buklod-empire/game/empire_ota_runtime_test.gd',path.join(dir,'scripts/test.gd'));
writeFileSync(path.join(dir,'project.godot'),'config_version=5\n[application]\nconfig/name="EmpireOTARuntimeTest"\n');
writeFileSync(path.join(dir,'data/ota_fixture.json'),'embedded');
const {privateKey,publicKey}=generateKeyPairSync('rsa',{modulusLength:2048});
const key=publicKey.export({type:'spki',format:'pem'});
const base='a'.repeat(64), runtime='empire-godot-4.7.2-r1',channel='dev';
writeFileSync(path.join(dir,'empire-ota/config.json'),JSON.stringify({schema:1,base,runtime,channel,key}));
const fixture=path.join(dir,'fixtures');
const hash=b=>createHash('sha256').update(b).digest('hex');
function pack(name,sequence,file,body,overrides={}){
 const content=path.join(fixture,'tmp');
 mkdirSync(path.dirname(path.join(content,file)),{recursive:true});
 writeFileSync(path.join(content,file),body);
 const zip=path.join(fixture,name+'.zip');
 execFileSync('zip',['-q','-X',zip,file],{cwd:content});
 rmSync(content,{recursive:true,force:true});
 const bytes=readFileSync(zip);
 const payload=Buffer.from(JSON.stringify({schema:1,package:'org.mzbministry.buklod.empire',channel,runtime,base,sequence,bytes:bytes.length,sha256:hash(bytes),...overrides}));
 const envelope={payload:payload.toString('base64'),signature:sign('sha256',payload,privateKey).toString('base64')};
 writeFileSync(path.join(fixture,name+'.json'),JSON.stringify(envelope));
 return envelope;
}
const valid=pack('v1',1,'data/ota_fixture.json','updated-v1');
pack('v2',2,'data/ota_fixture.json','updated-v2');
pack('v3',3,'data/ota_fixture.json','updated-v3');
pack('wrong-channel',4,'data/ota_fixture.json','bad',{channel:'production'});
pack('wrong-runtime',4,'data/ota_fixture.json','bad',{runtime:'wrong'});
pack('protected',4,'scripts/empire_ota.gd','bad');
writeFileSync(path.join(fixture,'tampered.json'),JSON.stringify({...valid,signature:Buffer.alloc(256,5).toString('base64')}));
console.log('ISOLATED_OTA_TEST_FIXTURES_READY');
