const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('src/lib/clusterDirectoryCache.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const context = { exports: {} }; vm.runInNewContext(compiled.outputText, context);
(async () => {
  let now = 1000;
  const cache = context.exports.createClusterDirectoryCache(() => now);
  cache.selectOwner('a');
  let calls = 0;
  const fetcher = async () => { calls++; return ['a']; };
  const first = cache.read('a', 'mine', fetcher);
  assert.equal(first, cache.read('a', 'mine', fetcher));
  await first;
  await cache.read('a', 'mine', fetcher);
  assert.equal(calls, 1, 'fresh return does not refetch');
  now += 31000;
  assert.equal(cache.peek('a', 'mine')[0], 'a', 'stale data remains visible');
  await cache.read('a', 'mine', async () => { throw new Error('offline'); }).catch(() => {});
  assert.equal(cache.peek('a', 'mine')[0], 'a', 'failed refresh preserves content');
  await cache.read('a', 'mine', fetcher, true);
  assert.equal(calls, 2, 'manual refresh bypasses freshness');
  let resolveOld;
  const old = cache.read('a', 'pending', () => new Promise(resolve => { resolveOld = resolve; }));
  await Promise.resolve();
  cache.selectOwner('b');
  assert.equal(cache.peek('b', 'mine'), undefined);
  cache.selectOwner('a');
  resolveOld(['old']); await old;
  assert.equal(cache.peek('a', 'pending'), undefined, 'old account generation cannot repopulate');
  await cache.read('a', 'mine', fetcher);
  for (let i = 0; i < 20; i++) await cache.read('a', `search:${i}`, fetcher);
  assert.ok(cache.peek('a', 'mine'), 'bounded searches preserve membership cache');
  assert.equal(cache.peek('a', 'search:0'), undefined);
  now += 301000;
  assert.equal(cache.peek('a', 'mine'), undefined, 'expired entries are not rendered');
  cache.invalidate();
  await cache.read('a', 'mine', fetcher);
  assert.ok(cache.peek('a', 'mine'));
  cache.selectOwner('');
  assert.equal(cache.peek('a', 'mine'), undefined, 'logout clears account data');
  await assert.rejects(cache.read('', 'mine', fetcher));

  for (const file of ['src/app/clusters/index.tsx', 'src/app/scope/index.tsx', 'src/components/BuklodHomeFaithPanel.tsx', 'src/components/BuklodScopeBuklodLessonPanel.tsx']) {
    const result = ts.transpileModule(fs.readFileSync(file, 'utf8'), { fileName: file, reportDiagnostics: true, compilerOptions: { jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2020 } });
    assert.equal(result.diagnostics?.filter(d => d.category === ts.DiagnosticCategory.Error).length, 0, file);
  }
  console.log('PASS: cache deduplication, freshness, offline retention, forced refresh, account isolation, stale request rejection, bounded size, expiry, logout; four TSX syntax checks.');
})().catch(error => { console.error(error); process.exitCode = 1; });
